#!/usr/bin/env python3
"""Generate the Flutter theme, the canvas CSS and the engine's signature
colors from design/tokens.json.

Usage:
    python3 tools/gen_tokens.py          # rewrite the generated files
    python3 tools/gen_tokens.py --check  # exit 1 if they are out of date (CI)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
DART = ROOT / "app" / "lib" / "design" / "tokens.g.dart"
CSS = ROOT / "design" / "tokens.css"
RUST = ROOT / "core" / "src" / "tokens_g.rs"

HEADER = "GENERATED by tools/gen_tokens.py from design/tokens.json. Do not edit by hand."


def kebab(name: str) -> str:
    return "".join("-" + c.lower() if c.isupper() else c for c in name)


def dart_color(hex_: str) -> str:
    """#RRGGBB, or #RRGGBBAA for a translucent color."""
    h = hex_.lstrip("#").upper()
    alpha = h[6:] or "FF"
    return "Color(0x" + alpha + h[:6] + ")"


def num(v) -> str:
    return repr(float(v))


def gen_dart(t: dict) -> str:
    roles = list(t["color"]["light"].keys())
    out = [f"// {HEADER}", "// ignore_for_file: public_member_api_docs", "",
           "import 'package:flutter/widgets.dart';", ""]

    out.append("/// Theme role colors, identical to the canvas design system.")
    out.append("@immutable")
    out.append("class PiumaColors {")
    out.append("  const PiumaColors({")
    out += [f"    required this.{r}," for r in roles]
    out.append("  });")
    out.append("")
    out += [f"  final Color {r};" for r in roles]
    for mode in ("light", "dark"):
        out.append("")
        out.append(f"  static const {mode} = PiumaColors(")
        out += [f"    {r}: {dart_color(t['color'][mode][r])}," for r in roles]
        out.append("  );")
    out.append("}")
    out.append("")

    out.append("/// Account colors (the dot next to each message).")
    out.append("abstract final class PiumaAccountColors {")
    for name, hex_ in t["account"].items():
        out.append(f"  static const {name} = {dart_color(hex_)};")
    names = ", ".join(t["account"].keys())
    line = f"  static const all = <Color>[{names}];"
    if len(line) <= 80:
        out.append(line)
    else:
        # As dart format writes a list too long for one line.
        out.append("  static const all = <Color>[")
        out.extend(f"    {name}," for name in t["account"])
        out.append("  ];")
    out.append("}")
    out.append("")

    sig = t["signature"]
    out.append("/// Signature accent colors, by name; dark is for previews only.")
    out.append("abstract final class PiumaSignatureColors {")
    for mode in ("light", "dark"):
        out.append(f"  static const {mode} = <String, Color>{{")
        for name, hex_ in sig[mode].items():
            out.append(f"    '{name}': {dart_color(hex_)},")
        out.append("  };")
    out.append("}")
    out.append("")

    tint = t["tint"]
    out.append("/// Quiet backgrounds for things with no picture of their own.")
    out.append("abstract final class PiumaTints {")
    for mode in ("light", "dark"):
        out.append(f"  static const {mode} = <Color>[")
        for name, hex_ in tint[mode].items():
            out.append(f"    {dart_color(hex_)}, // {name}")
        out.append("  ];")
    out.append("}")
    out.append("")

    ink = t["tintInk"]
    names = list(ink["light"])
    out.append("/// Text and icons on a tint, by the tint's name.")
    out.append("class PiumaTintInk {")
    out.append("  const PiumaTintInk({")
    for n in names:
        out.append(f"    required this.{n},")
    out.append("  });")
    out.append("")
    for n in names:
        out.append(f"  final Color {n};")
    out.append("")
    for mode in ("light", "dark"):
        out.append(f"  static const {mode} = PiumaTintInk(")
        for n in names:
            out.append(f"    {n}: {dart_color(ink[mode][n])},")
        out.append("  );")
    out.append("}")
    out.append("")

    label = t["label"]
    out.append("/// A label's pill: its background and its words, by the label's color.")
    out.append("abstract final class PiumaLabelColors {")
    for mode in ("light", "dark"):
        out.append(f"  static const {mode} = <String, (Color, Color)>{{")
        for name, pair in label[mode].items():
            out.append(f"    '{name}': ({dart_color(pair['bg'])}, {dart_color(pair['ink'])}),")
        out.append("  };")
    out.append("}")
    out.append("")

    out.append("abstract final class PiumaFonts {")
    out.append(f"  static const sans = '{t['font']['sans']}';")
    out.append(f"  static const mono = '{t['font']['mono']}';")
    out.append("}")
    out.append("")

    out.append("/// Type scale. Color is applied by the theme.")
    out.append("abstract final class PiumaType {")
    for name, s in t["type"].items():
        family = "PiumaFonts.mono" if s.get("mono") else "PiumaFonts.sans"
        ls = s["letterSpacing"] * s["size"]
        out.append(f"  static const {name} = TextStyle(")
        out.append(f"    fontFamily: {family},")
        out.append(f"    fontSize: {num(s['size'])},")
        out.append(f"    fontWeight: FontWeight.w{s['weight']},")
        out.append(f"    letterSpacing: {num(round(ls, 3))},")
        out.append(f"    height: {num(s['height'])},")
        out.append("  );")
    upper = [n for n, s in t["type"].items() if s.get("uppercase")]
    out.append("")
    out.append("  /// Styles shown in uppercase.")
    out.append("  static const uppercase = <TextStyle>[" + ", ".join(upper) + "];")
    out.append("}")
    out.append("")

    out.append("abstract final class PiumaRadius {")
    for name, v in t["radius"].items():
        out.append(f"  static const {name} = {num(v)};")
    out.append("}")
    out.append("")

    out.append("/// Spacing, base 4.")
    out.append("abstract final class PiumaSpace {")
    for v in t["space"]:
        out.append(f"  static const s{v} = {num(v)};")
    out.append("}")
    out.append("")

    m = t["motion"]
    c = m["curve"]
    out.append("/// Fluid motion: springs for what moves, `curve` for fades (see tokens.json).")
    out.append("abstract final class PiumaMotion {")
    out.append(f"  static const curve = Cubic({num(c[0])}, {num(c[1])}, {num(c[2])}, {num(c[3])});")
    for key, val in m.items():
        if key.startswith("$") or key == "curve":
            continue
        if key.endswith("Ms"):
            out.append(f"  static const {key[:-2]} = Duration(milliseconds: {val});")
        else:
            out.append(f"  static const {key} = {num(val)};")
    out.append("}")
    out.append("")
    return "\n".join(out)


def gen_css(t: dict) -> str:
    out = [f"/* {HEADER} */", ":root {"]
    for r, v in t["color"]["light"].items():
        out.append(f"  --{kebab(r)}: {v};")
    for name, v in t["account"].items():
        out.append(f"  --account-{name}: {v};")
    for name, v in t["tint"]["light"].items():
        out.append(f"  --tint-{name}: {v};")
    for name, v in t["tintInk"]["light"].items():
        out.append(f"  --tint-ink-{name}: {v};")
    for name, pair in t["label"]["light"].items():
        out.append(f"  --label-{name}-bg: {pair['bg']};")
        out.append(f"  --label-{name}-ink: {pair['ink']};")
    out.append(f"  --font-sans: '{t['font']['sans']}', system-ui, sans-serif;")
    out.append(f"  --font-mono: '{t['font']['mono']}', ui-monospace, monospace;")
    for name, v in t["radius"].items():
        out.append(f"  --radius-{name}: {v}px;")
    for v in t["space"]:
        out.append(f"  --space-{v}: {v}px;")
    m = t["motion"]
    out.append("  --ease: cubic-bezier(" + ",".join(str(x) for x in m["curve"]) + ");")
    for key, val in m.items():
        if key.endswith("Ms"):
            out.append(f"  --motion-{kebab(key[:-2])}: {val}ms;")
    out.append("}")
    out.append("")
    out.append("[data-theme=\"dark\"] {")
    for r, v in t["color"]["dark"].items():
        out.append(f"  --{kebab(r)}: {v};")
    for name, v in t["tint"]["dark"].items():
        out.append(f"  --tint-{name}: {v};")
    for name, v in t["tintInk"]["dark"].items():
        out.append(f"  --tint-ink-{name}: {v};")
    for name, pair in t["label"]["dark"].items():
        out.append(f"  --label-{name}-bg: {pair['bg']};")
        out.append(f"  --label-{name}-ink: {pair['ink']};")
    out.append("}")
    out.append("")
    return "\n".join(out)


def gen_rust(t: dict) -> str:
    light = t["color"]["light"]
    out = [f"// {HEADER}", "",
           "//! Colors the engine writes into email: signatures, and the paper of an\n//! original layout.", "",
           "/// Signature accents by name, as `#RRGGBB`.",
           "pub const SIGNATURE_ACCENTS: &[(&str, &str)] = &["]
    for name, hex_ in t["signature"]["light"].items():
        out.append(f'    ("{name}", "{hex_}"),')
    out.append("];")
    out.append("")
    out.append("/// Text and secondary text of the light theme.")
    out.append(f'pub const TEXT: &str = "{light["fg"]}";')
    out.append(f'pub const MUTED: &str = "{light["muted"]}";')
    out.append(f'pub const ON_ACCENT: &str = "{light["onAccent"]}";')
    out.append("")
    out.append("/// The paper an email's original layout sits on, and the grey of an")
    out.append("/// image still waiting; light in both themes, as senders design for it.")
    out.append(f'pub const PAPER: &str = "{light["page"]}";')
    out.append(f'pub const PLACEHOLDER: &str = "{light["placeholder"]}";')
    out.append("")
    return "\n".join(out)


def main() -> int:
    tokens = json.loads(SRC.read_text(encoding="utf-8"))
    outputs = {DART: gen_dart(tokens), CSS: gen_css(tokens), RUST: gen_rust(tokens)}
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"Out of date: {p.relative_to(ROOT)} (run python3 tools/gen_tokens.py)")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"Wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
