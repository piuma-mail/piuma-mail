#!/usr/bin/env python3
"""List the Rust crates that ship in the app, with their licenses.

Writes THIRD_PARTY_RUST.md from `cargo metadata`: every crate reachable from the
workspace through normal dependencies (dev and build dependencies don't ship).
Run after changing Cargo.lock; `--check` fails if the file is out of date.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_RUST.md"
# Crates whose Cargo.toml has no license field, read from their LICENSE file.
LICENSE_FILES = {"allo-isolate": "Apache-2.0"}


def shipped_crates():
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    seen, todo = set(), list(workspace)
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            if dep["pkg"] in seen:
                continue
            if any(kind["kind"] is None for kind in dep["dep_kinds"]):
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return sorted(
        (packages[i] for i in seen - workspace),
        key=lambda p: (p["name"].lower(), p["version"]),
    )


def render(crates):
    lines = [
        "# Rust crates in Piuma Mail",
        "",
        "Generated by `tools/gen_rust_licenses.py` from `Cargo.lock`; do not edit by hand. These are the crates",
        "compiled into the app's engine. Each keeps its own license; the full texts come with each crate's source.",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    for p in crates:
        name = p["name"]
        if p.get("repository"):
            name = f"[{name}]({p['repository']})"
        lines.append(f"| {name} | {p['version']} | {p.get('license') or LICENSE_FILES.get(p['name'], 'see crate')} |")
    return "\n".join(lines) + "\n"


def main():
    text = render(shipped_crates())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("THIRD_PARTY_RUST.md is out of date: run python3 tools/gen_rust_licenses.py")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
