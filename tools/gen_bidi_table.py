#!/usr/bin/env python3
"""Writes app/lib/widgets/bidi_table.g.dart: which characters are strong
for Unicode's bidirectional algorithm, by Bidi_Class.

Only L (left to right) and R or AL (right to left) decide a paragraph's
direction (rule P2). Everything else, digits of every kind (EN, AN),
separators and terminators (ES, ET, CS), combining marks (NSM), format
characters (BN), spaces and other neutrals, is skipped.

The table is a list of run starts covering every code point, with one
letter per run: "L", "R" or "N" (neither). Unassigned code points join
the run before them. It comes from the Python interpreter's Unicode
database, so regenerate it with a recent Python after a Unicode release:

    python3 tools/gen_bidi_table.py

The output is already as `dart format` leaves it, so regenerating with the
same Unicode version gives the same bytes. The data is the Unicode
Character Database's, under the Unicode License v3: the generated file
carries its notice, and the full text is in
app/assets/licenses/Unicode-3.0.txt (shown on the app's licenses screen,
listed in THIRD_PARTY.md).
"""

import pathlib
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/lib/widgets/bidi_table.g.dart"
LICENSE = ROOT / "app/assets/licenses/Unicode-3.0.txt"


def strength(cp):
    b = unicodedata.bidirectional(chr(cp))
    if b == "":
        return None
    if b in ("R", "AL"):
        return "R"
    if b == "L":
        return "L"
    return "N"


def runs():
    out = []
    for cp in range(0x110000):
        s = strength(cp)
        if s is None:
            continue
        if out and out[-1][1] == s:
            continue
        out.append((cp if out else 0, s))
    return out


def notice():
    """The license's copyright and permission notice, as Dart comments."""
    lines = LICENSE.read_text(encoding="utf-8").rstrip("\n").split("\n")
    return "".join(f"// {line}\n" if line else "//\n" for line in lines)


def main():
    rs = runs()
    kinds = "".join(s for _, s in rs)
    # One element per line with a trailing comma, as `dart format` puts a
    # list that doesn't fit on one line.
    starts = "".join(f"  0x{start:X},\n" for start, _ in rs)
    letters = "\n".join(
        f"    '{kinds[i:i + 70]}'" for i in range(0, len(kinds), 70)
    )
    OUT.write_text(
        "// GENERATED by tools/gen_bidi_table.py from Unicode "
        f"{unicodedata.unidata_version}. Do not edit.\n"
        "//\n"
        "// Derived from the Unicode Character Database (Bidi_Class):\n"
        "//\n"
        f"{notice()}"
        "\n"
        "// ignore_for_file: lines_longer_than_80_chars\n\n"
        "/// Where each run of [bidiStrongKinds] starts, ascending.\n"
        "const List<int> bidiRunStarts = <int>[\n"
        f"{starts}"
        "];\n\n"
        "/// One letter per run: L, R (R or AL) or N (not strong).\n"
        "const String bidiStrongKinds =\n"
        f"{letters};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
